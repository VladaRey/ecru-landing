// PostHog. Один файл на всю аналітику: ключ, регіон і налаштування живуть
// тут, а сторінка про них не знає — у розмітці лише <script src>.
//
// Ключ проєкту публічний за задумом: ним можна тільки писати події, читати
// чи видаляти — ні. Тому він лежить у репозиторії, а не в секретах.
const KEY = 'phc_xUirmvmPzqhCLjv9J9cjDGTxwjDgdUVESorqD3kSXY4m';
const HOST = 'https://eu.i.posthog.com';

// Статику PostHog віддає з сусіднього піддомену: eu.i → eu-assets.i.
const ASSETS = HOST.replace('.i.posthog.com', '-assets.i.posthog.com');

// Замість офіційного мініфікованого сніпета — звичайний тег. Сніпет
// потрібен лише для того, щоб події, зняті до завантаження array.js, не
// загубились; тут ловити нічого: єдина подія настає тоді, коли людина
// натисне кнопку, а це вже після завантаження.
const script = document.createElement('script');
script.src = `${ASSETS}/static/array.js`;
script.async = true;
script.crossOrigin = 'anonymous';

// Форма мусить знати, чи аналітика справді доїхала: показати «Дякуємо»,
// коли блокувальник зрізав запит, — це та сама мовчазна брехня, якої
// waitlist.js уникає з першого дня. Обіцянка каже правду, а не надію.
window.analyticsReady = new Promise((resolve) => {
  // Блокувальники поводяться по-різному: одні дають error, інші лишають
  // запит висіти. Час чекання обмежений, щоб кнопка не залипла назавжди.
  const timer = setTimeout(() => resolve(false), 5000);

  const settle = (ok) => {
    clearTimeout(timer);
    resolve(ok);
  };

  script.addEventListener('error', () => settle(false));
  script.addEventListener('load', () => {
    window.posthog.init(KEY, {
      api_host: HOST,

      // Ні куків, ні localStorage. Підвал сторінки обіцяє відвідувачу, що
      // вона не ставить стежних куків, — обіцянка лишається правдою, а
      // Європі не треба банера згоди. Ціна: кожне завантаження сторінки
      // PostHog бачить як нову людину, тож «унікальні» там рахують візити.
      persistence: 'memory',

      // Профіль людини заводиться тільки після identify, тобто лише на тих,
      // хто сам залишив пошту. Решта лишається безіменними подіями.
      person_profiles: 'identified_only',

      // array.js за замовчуванням дотягує з мережі ще кілька модулів —
      // опитування, «мертві кліки», web vitals. Жодним із них сторінка не
      // користується, тож вони були б трьома зайвими запитами до чужого
      // домену на лендингу, де решта всього лежить локально.
      //
      // Прапорець вимикає саме дозавантаження, а не збір: кліки й перегляди
      // рахує сам array.js, і вони лишаються на місці.
      disable_external_dependency_loading: true,

      // Опитування вимикаються окремо: без цього PostHog однаково сходить
      // по їхній список, навіть коли скрипт для показу не завантажився.
      disable_surveys: true,

      // Швидкість завантаження сторінки збирає не PostHog, а Lighthouse,
      // коли він потрібен. Тут це просто зайвий трафік.
      capture_performance: false,
    });
    settle(true);
  });
});

document.head.appendChild(script);
